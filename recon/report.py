"""Report generator module for JSON and Markdown outputs.

Ensures all findings are prominently labeled as 'tool-reported, unverified'.
Documents scan metadata, scope boundaries, and explicit limitations.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List

from recon.config import ReconConfig
from recon.parsers.httpx_parser import HttpService
from recon.parsers.nmap_parser import HostPorts
from recon.parsers.nuclei_parser import NucleiFinding
from recon.runner import ToolCheckResult
from recon.scope import Scope

AUTHORISATION_BANNER = (
    "================================================================================\n"
    "                     AUTHORISED SECURITY ASSESSMENT NOTICE                     \n"
    " This tool is a defensive asset inventory prototype intended strictly for     \n"
    " authorised assessments on owned assets or explicit in-scope targets.         \n"
    " All findings herein are TOOL-REPORTED AND UNVERIFIED. No exploits executed.   \n"
    "================================================================================"
)

LIMITATIONS_TEXT = """### Assessment Limitations & Boundaries

1. **Defensive Inventory Only**: This assessment was executed using a prototype pipeline designed for attack-surface inventory. It does not exploit vulnerabilities, craft attack payloads, or evaluate secondary impact.
2. **Unverified Findings**: All findings and template matches generated by external tools (e.g. Nuclei, Nmap) are reported directly as tool outputs and remain strictly unverified until confirmed by manual validation.
3. **Non-Intrusive Filter**: In adherence to safety guidelines, all intrusive, denial-of-service (DoS), and fuzzing template tags were excluded.
4. **Scope Boundaries**: Passive and active enumeration was restricted strictly to the declared scope allowlist. Out-of-scope subdomains, adjacent networks, and non-target cloud services were excluded.
5. **Partial Coverage**: Scans were executed against conservative port profiles (top ports) and rate limits. Services on non-standard ports or behind Web Application Firewalls (WAF) may not be detected.
"""


class ReportGenerator:
    """Produces structured JSON and human-readable Markdown reports."""

    def __init__(
        self,
        config: ReconConfig,
        scope: Scope,
        tool_status: Dict[str, ToolCheckResult],
        stage_status: Dict[str, str],
        subdomains: List[str],
        http_services: List[HttpService],
        host_ports: List[HostPorts],
        findings: List[NucleiFinding],
        start_time: datetime,
        end_time: datetime,
    ) -> None:
        self.config = config
        self.scope = scope
        self.tool_status = tool_status
        self.stage_status = stage_status
        self.subdomains = subdomains
        self.http_services = http_services
        self.host_ports = host_ports
        self.findings = findings
        self.start_time = start_time
        self.end_time = end_time

    def generate_json(self, output_path: Path) -> Dict[str, Any]:
        """Compile and write report.json."""
        # Group findings by severity
        findings_by_severity: Dict[str, List[Dict[str, Any]]] = {
            "critical": [],
            "high": [],
            "medium": [],
            "low": [],
            "info": [],
        }

        for f in self.findings:
            sev = f.severity.lower()
            if sev not in findings_by_severity:
                findings_by_severity[sev] = []
            findings_by_severity[sev].append(f.to_dict())

        report_data = {
            "metadata": {
                "authorisation_confirmed": self.config.authorized,
                "banner": AUTHORISATION_BANNER,
                "start_time_utc": self.start_time.isoformat(),
                "end_time_utc": self.end_time.isoformat(),
                "duration_seconds": round((self.end_time - self.start_time).total_seconds(), 2),
                "scope_file": str(self.config.scope_file),
                "in_scope_entries": self.scope.raw_entries,
            },
            "tool_environment": {
                name: {
                    "installed": t.installed,
                    "path": t.path,
                    "version": t.version_output,
                    "error": t.error_message,
                }
                for name, t in self.tool_status.items()
            },
            "stages": self.stage_status,
            "results_summary": {
                "discovered_subdomains_count": len(self.subdomains),
                "live_http_services_count": len(self.http_services),
                "scanned_hosts_count": len(self.host_ports),
                "total_open_ports_count": sum(len(h.ports) for h in self.host_ports),
                "total_findings_count": len(self.findings),
            },
            "inventory": {
                "subdomains": self.subdomains,
                "http_services": [s.to_dict() for s in self.http_services],
                "host_ports": [h.to_dict() for h in self.host_ports],
            },
            "findings_by_severity": findings_by_severity,
            "all_findings": [f.to_dict() for f in self.findings],
            "limitations": LIMITATIONS_TEXT.strip(),
        }

        output_path.write_text(json.dumps(report_data, indent=2), encoding="utf-8")
        return report_data

    def generate_markdown(self, output_path: Path) -> str:
        """Compile and write human-readable report.md."""
        md: List[str] = []

        md.append("# Reconnaissance & Attack-Surface Inventory Report")
        md.append(f"\n```\n{AUTHORISATION_BANNER}\n```\n")

        # Overview Table
        md.append("## 1. Execution Metadata")
        md.append(f"- **Scan Date (UTC):** {self.start_time.strftime('%Y-%m-%d %H:%M:%S')} to {self.end_time.strftime('%Y-%m-%d %H:%M:%S')}")
        md.append(f"- **Duration:** {round((self.end_time - self.start_time).total_seconds(), 2)}s")
        md.append(f"- **Scope File:** `{self.config.scope_file}`")
        md.append(f"- **Authorization Confirmed:** `{'YES (--i-have-authorization provided)' if self.config.authorized else 'NO'}`")
        md.append(f"- **Configured Scope Targets:** {', '.join(f'`{e}`' for e in self.scope.raw_entries) or 'None'}")

        # Tools and Pipeline Stages
        md.append("\n## 2. Tool Environment & Pipeline Stages")
        md.append("| Tool | Available | Version / Binary Path | Stage Execution Status |")
        md.append("|---|---|---|---|")
        for tool_name in ["subfinder", "httpx", "nmap", "nuclei"]:
            t = self.tool_status.get(tool_name)
            installed = "Yes" if (t and t.installed) else "No"
            ver = (t.version_output or t.path or t.error_message or "N/A") if t else "Not checked"
            status = self.stage_status.get(tool_name, "Not run")
            md.append(f"| `{tool_name}` | {installed} | `{ver}` | {status} |")

        # Subdomains Inventory
        md.append("\n## 3. Discovered In-Scope Subdomains")
        if self.subdomains:
            md.append(f"Discovered **{len(self.subdomains)}** in-scope subdomain(s):\n")
            for sub in sorted(self.subdomains):
                md.append(f"- `{sub}`")
        else:
            md.append("*No subdomains discovered or stage skipped.*")

        # Live HTTP Services
        md.append("\n## 4. Live HTTP Services (httpx)")
        if self.http_services:
            md.append("| Host | Status | Title | Technologies | URL |")
            md.append("|---|---|---|---|---|")
            for svc in self.http_services:
                tech_str = ", ".join(svc.technologies) if svc.technologies else "-"
                title_str = (svc.title or "-").replace("|", "\\|")
                md.append(f"| `{svc.host}` | {svc.status_code or '-'} | {title_str} | {tech_str} | [{svc.url}]({svc.url}) |")
        else:
            md.append("*No live HTTP services detected or stage skipped.*")

        # Port Scan Results
        md.append("\n## 5. Port and Service Inventory (Nmap)")
        if self.host_ports and any(h.ports for h in self.host_ports):
            md.append("| Host | IP | Port / Protocol | Service | Product / Version |")
            md.append("|---|---|---|---|---|")
            for h in self.host_ports:
                for p in h.ports:
                    prod_ver = f"{p.product or ''} {p.version or ''}".strip() or "-"
                    md.append(f"| `{h.host}` | `{h.ip or '-'}` | `{p.port}/{p.protocol}` | `{p.service}` | {prod_ver} |")
        else:
            md.append("*No open ports detected on in-scope hosts or stage skipped.*")

        # Findings
        md.append("\n## 6. Template Exposure Findings (Nuclei)")
        md.append("> [!NOTE]\n> **Status:** Tool-reported, unverified. Requires manual confirmation.\n")

        if self.findings:
            # Group by severity
            sev_order = ["critical", "high", "medium", "low", "info"]
            grouped: Dict[str, List[NucleiFinding]] = {s: [] for s in sev_order}
            for f in self.findings:
                s = f.severity.lower()
                grouped.setdefault(s, []).append(f)

            for sev in sev_order:
                items = grouped.get(sev, [])
                if not items:
                    continue
                md.append(f"### Severity: {sev.upper()} ({len(items)} items)")
                md.append("| Template ID | Name | Matched At | Description |")
                md.append("|---|---|---|---|")
                for item in items:
                    desc = (item.description or "-").replace("\n", " ").replace("|", "\\|")
                    if len(desc) > 80:
                        desc = desc[:77] + "..."
                    md.append(f"| `{item.template_id}` | {item.name} | `{item.matched_at}` | {desc} |")
                md.append("")
        else:
            md.append("*No template matches reported or stage skipped.*")

        # Limitations
        md.append("\n## 7. Limitations")
        md.append(LIMITATIONS_TEXT)

        content = "\n".join(md)
        output_path.write_text(content, encoding="utf-8")
        return content
