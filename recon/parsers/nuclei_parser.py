"""Parser for ProjectDiscovery Nuclei JSON-lines output."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Union


@dataclass
class NucleiFinding:
    """Represents an unverified template-reported finding from Nuclei."""

    template_id: str
    name: str
    severity: str
    matched_at: str
    host: str
    description: Optional[str] = None
    tags: List[str] = field(default_factory=list)
    reference: List[str] = field(default_factory=list)
    curl_command: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "template_id": self.template_id,
            "name": self.name,
            "severity": self.severity.lower(),
            "matched_at": self.matched_at,
            "host": self.host,
            "description": self.description,
            "tags": self.tags,
            "reference": self.reference,
            "verification_status": "tool-reported, unverified",
        }


def parse_nuclei_jsonl(content_or_file: Union[str, Path]) -> List[NucleiFinding]:
    """Parse JSON-lines output generated by Nuclei.

    Deduplicates findings by (template_id, matched_at).
    """
    if isinstance(content_or_file, Path) or (
        isinstance(content_or_file, str) and Path(content_or_file).is_file()
    ):
        raw_text = Path(content_or_file).read_text(encoding="utf-8")
    else:
        raw_text = str(content_or_file)

    findings: List[NucleiFinding] = []
    seen = set()

    for line in raw_text.splitlines():
        line = line.strip()
        if not line:
            continue

        try:
            entry = json.loads(line)
        except json.JSONDecodeError:
            continue

        template_id = entry.get("template-id") or entry.get("templateID", "")
        matched_at = entry.get("matched-at") or entry.get("matched", "")
        dedup_key = (template_id, matched_at)
        if dedup_key in seen:
            continue
        seen.add(dedup_key)

        info = entry.get("info", {})
        severity = info.get("severity", "info")
        name = info.get("name", template_id)
        description = info.get("description")
        tags = info.get("tags", [])
        if isinstance(tags, str):
            tags = [t.strip() for t in tags.split(",") if t.strip()]

        ref = info.get("reference", [])
        if isinstance(ref, str):
            ref = [ref]

        host = entry.get("host", "")
        if not host and "://" in matched_at:
            host = matched_at.split("://")[1].split("/")[0]

        findings.append(
            NucleiFinding(
                template_id=template_id,
                name=name,
                severity=severity,
                matched_at=matched_at,
                host=host or "unknown",
                description=description,
                tags=tags,
                reference=ref,
                curl_command=entry.get("curl-command"),
            )
        )

    return findings
