"""Parser for ProjectDiscovery httpx JSON-lines output."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

from recon.scope import validate_target


@dataclass
class HttpService:
    """Represents an HTTP/HTTPS service discovered by httpx."""

    url: str
    host: str
    status_code: Optional[int] = None
    title: Optional[str] = None
    technologies: List[str] = field(default_factory=list)
    webserver: Optional[str] = None
    content_length: Optional[int] = None
    redirect_chain: List[str] = field(default_factory=list)
    scheme: str = "http"
    port: Optional[int] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "url": self.url,
            "host": self.host,
            "status_code": self.status_code,
            "title": self.title,
            "technologies": self.technologies,
            "webserver": self.webserver,
            "content_length": self.content_length,
            "redirect_chain": self.redirect_chain,
            "scheme": self.scheme,
            "port": self.port,
        }


def parse_httpx_jsonl(content_or_file: Union[str, Path]) -> List[HttpService]:
    """Parse JSON-lines output generated by httpx."""
    if isinstance(content_or_file, Path) or (
        isinstance(content_or_file, str) and Path(content_or_file).is_file()
    ):
        raw_text = Path(content_or_file).read_text(encoding="utf-8")
    else:
        raw_text = str(content_or_file)

    services: List[HttpService] = []
    seen_urls = set()

    for line in raw_text.splitlines():
        line = line.strip()
        if not line:
            continue

        try:
            entry = json.loads(line)
        except json.JSONDecodeError:
            continue

        url = entry.get("url", "")
        if not url or url in seen_urls:
            continue
        seen_urls.add(url)

        # Host extraction
        host = entry.get("input", "") or entry.get("host", "")
        if not host and "://" in url:
            host = url.split("://")[1].split("/")[0].split(":")[0]

        # Clean tech list
        tech = entry.get("tech") or entry.get("technologies") or []
        if isinstance(tech, str):
            tech = [tech]

        # Port parsing
        port_raw = entry.get("port")
        port = int(port_raw) if port_raw is not None else None

        # Chain parsing
        chain = entry.get("chain") or entry.get("chain_status_codes") or []
        if isinstance(chain, str):
            chain = [chain]

        services.append(
            HttpService(
                url=url,
                host=host,
                status_code=entry.get("status_code") or entry.get("status-code"),
                title=entry.get("title"),
                technologies=sorted(set(str(t) for t in tech if t)),
                webserver=entry.get("webserver"),
                content_length=entry.get("content_length"),
                redirect_chain=[str(c) for c in chain],
                scheme=entry.get("scheme", "http"),
                port=port,
            )
        )

    return services
